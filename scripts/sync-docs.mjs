import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {DOMAINS,LESSONS,QUESTIONS,COMMAND_GUIDES,COMMAND_SOURCES,LABS} from '../src/app/data.ts';
import {BLUEPRINT,BLUEPRINT_SOURCE,BLUEPRINT_VERSION} from '../src/app/blueprint.data.ts';
import {BOOKS,TEXTBOOK_REVIEWS} from '../src/app/textbook.data.ts';
import {GLOSSARY} from '../src/app/glossary.data.ts';
import {coverageDocuments} from './lib/assessment-coverage.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const args=process.argv.slice(2);
if(args.some(a=>a!=='--check'))throw Error('Usage: node --experimental-strip-types scripts/sync-docs.mjs [--check]');
const check=args.includes('--check');
const begin='<!-- BEGIN GENERATED CURRICULUM STATS -->',end='<!-- END GENERATED CURRICULUM STATS -->';
const topics=Object.values(BLUEPRINT).flatMap(o=>o.subtopics);
const moduleCount=Object.values(COMMAND_GUIDES).reduce((n,g)=>n+g.blocks.length,0);
const sections=Object.values(TEXTBOOK_REVIEWS).reduce((n,r)=>n+r.sections.length,0);
const base='https://ianlin-smci.github.io/ccna-study-lab/';
const route=(id,section='')=>base+'#/lesson/'+id+(section?'/'+section:'');
const anchor=(kind,id)=>kind+'-'+id.replaceAll('.','-');
const text=value=>String(value).replaceAll('<','&lt;').replaceAll('>','&gt;');
const cell=value=>text(value??'').replaceAll('|','\\|').replace(/\r?\n/g,'<br>');
const link=(label,url)=>`[${text(label)}](${url})`;
const fence=code=>{
  const content=String(code),runs=[...content.matchAll(/`+/g)].map(m=>m[0].length);
  const mark='`'.repeat(Math.max(2,...runs)+1);
  return `${mark}text\n${content}${content.endsWith('\n')?'':'\n'}${mark}\n`;
};
const table=(headers,rows)=>[
  '| '+headers.map(cell).join(' | ')+' |',
  '| '+headers.map(()=>'---').join(' | ')+' |',
  ...rows.map(row=>'| '+row.map(cell).join(' | ')+' |')
].join('\n');
const stats=begin+'\n\n'+table(['Study material','Current content'],[
  ['Exam blueprint',`${DOMAINS.length} domains · ${LESSONS.length} objectives · ${topics.length} lettered subtopics`],
  ['Commands',`${moduleCount} platform-labeled command modules`],
  ['Practice',`${QUESTIONS.length} original questions · 60-question, 120-minute mock exams`],
  ['Textbook support',`${sections} explanation sections · ${Object.keys(TEXTBOOK_REVIEWS).length} worked review checks`],
  ['Glossary',`${GLOSSARY.length} abbreviation entries with optional definition hints`],
  ['Guided CLI',`${LABS.length} scripted lab exercises`]
])+'\n\n'+end;

for(const l of LESSONS){
  if(!BLUEPRINT[l.id]||!TEXTBOOK_REVIEWS[l.id]||!COMMAND_GUIDES[l.id])throw Error('Incomplete curriculum record: '+l.id);
  if(l.title!==BLUEPRINT[l.id].title)throw Error('Objective title mismatch: '+l.id);
}
const model={domains:DOMAINS,blueprint:BLUEPRINT,lessons:LESSONS,guides:COMMAND_GUIDES,sources:COMMAND_SOURCES,books:BOOKS,reviews:TEXTBOOK_REVIEWS};
const digest=createHash('sha256').update(JSON.stringify(model)).digest('hex');
const out=[];
const add=(...parts)=>{for(const p of parts)out.push(p,'');};
const heading=(level,label,id)=>{if(id)add(`<a id="${id}"></a>`);add('#'.repeat(level)+' '+text(label));};
heading(1,`Learning Path — CCNA 200-301 ${BLUEPRINT_VERSION}`);
add('<!-- Generated by scripts/sync-docs.mjs. Edit the curriculum source, then run npm run docs:sync. -->',`<!-- Curriculum SHA-256: ${digest} -->`);
add(`**${DOMAINS.length} domains · ${LESSONS.length} objectives · ${topics.length} lettered subtopics · ${moduleCount} command modules**`);
add('This is the Markdown shadow copy of the website’s Learning Path. Numbering and skill targets follow the linked Cisco blueprint; labels and explanations are independently worded. Textbook material supports the numbered exam objectives.');
add(link('Interactive Learning Path',base+'#/path')+' · '+link('Official v1.1 exam topics',BLUEPRINT_SOURCE)+' · '+link('Abbreviation glossary',base+'#/glossary')+' · '+link('Textbook alignment',base+'#/textbook'));
add('The snapshot includes lesson content, command examples, worked checks and lesson knowledge checks. The separate practice-question bank, flashcards and glossary are available on the site. Personal progress and notes are not part of this generated curriculum file.');
add('Run `npm run docs:sync` after curriculum edits. `npm run docs:check` verifies synchronization without writing files. Direct edits here are replaced on regeneration; keep personal study annotations separately.');
heading(2,'Scope and lab assumptions');
add('Use the exam version for your scheduled test. Match command examples to their stated platform, software, license and interfaces. Documentation review is not physical-device validation. The guided CLI and VLAN explorer are educational models; hands-on work belongs in a suitable simulator or supported lab.');
add('Each command block below preserves its source text and platform label. Management-workstation commands are separate from IOS XE commands. Additional concept examples may contain older syntax. A copied configuration needs the lab’s addresses, interfaces, credentials and topology.');
add('CLI reminder: `enable` enters privileged EXEC; `configure terminal` enters global configuration; interface/line commands enter submodes. `end` returns to privileged EXEC. Validate the result, then use `copy running-config startup-config` when saving is appropriate.');
heading(2,'Contents');
for(const d of DOMAINS){
  out.push(`- ${link(`${d.id}.0 ${d.name} — ${d.weight}%`, '#'+anchor('domain',d.id+'.0'))}`);
  for(const l of LESSONS.filter(l=>l.d===d.id)){
    out.push(`  - ${link(`${l.id} ${l.title}`, '#'+anchor('objective',l.id))}`);
    for(const t of BLUEPRINT[l.id].subtopics)out.push(`    - ${link(`${t.id} ${t.title}`, '#'+anchor('topic',t.id))}`);
  }
}
out.push('');
for(const d of DOMAINS){
  heading(2,`${d.id}.0 ${d.name} — ${d.weight}%`,anchor('domain',d.id+'.0'));
  add(text(d.desc));
  const domainLessons=LESSONS.filter(l=>l.d===d.id);
  add(`${domainLessons.length} objectives · ${domainLessons.reduce((n,l)=>n+BLUEPRINT[l.id].subtopics.length,0)} lettered subtopics`);
  for(const l of domainLessons){
    const b=BLUEPRINT[l.id],r=TEXTBOOK_REVIEWS[l.id],g=COMMAND_GUIDES[l.id];
    heading(3,`${l.id} — ${l.title}`,anchor('objective',l.id));
    add(`**Exam target:** ${text(b.skill)}.`,link('Open objective',route(l.id))+' · '+link('Open command guide',route(l.id,'commands')),text(l.intro));
    for(const t of b.subtopics){heading(4,`${t.id} — ${t.title}`,anchor('topic',t.id));add(link('Open this subtopic',route(l.id,t.id)),text(t.body));}
    heading(4,b.subtopics.length?'Objective overview':'Build your understanding');
    add(l.points.map(p=>'- '+text(p)).join('\n'));
    heading(4,'Supporting reading — Official Cert Guide, Second Edition');
    const reading=[];
    if(r.v1.length)reading.push(link('Volume 1 · Chapters '+r.v1.join(', '),BOOKS[1].url));
    if(r.v2.length)reading.push(link('Volume 2 · Chapters '+r.v2.join(', '),BOOKS[2].url));
    add('Suggested reading: '+reading.join(' · '));
    for(const s of r.sections){heading(5,s.heading);add(text(s.body));}
    heading(5,'Worked review check');
    add(text(r.exercise.prompt),'<details>\n<summary>Show the reasoning</summary>\n\n'+text(r.exercise.answer)+'\n\n</details>');
    heading(4,'Platform-labeled command guide');
    add(text(g.scope));
    if(g.coverage.length)add('**Covered features:** '+g.coverage.map(text).join('; ')+'.');
    if(g.note)add(text(g.note));
    if(g.topology){
      heading(5,'Walkthrough topology and addressing');
      add('**Devices:** '+g.topology.devices.map(text).join('; '),'**Link:** '+text(g.topology.link));
      add(table(['VLAN','Name','Subnet','Gateway','Hosts','Access ports'],g.topology.networks.map(n=>[n.id,n.name,n.subnet,n.gateway,n.hosts,n.ports])));
      add('**VLAN policy model:** With the example links and SVIs up, different hosts in the same VLAN use Layer 2 switching. With the source-SVI ACL policy applied, Users (10) and Servers (20) can route to each other; routed Guest (30) traffic to those peer networks is blocked. With that policy removed, the three connected SVIs can route. These are modelled outcomes, not live packet measurements.');
    }
    for(const block of g.blocks){
      heading(5,block.title);
      add(`**Category:** ${text(block.kind)}. **Platform/context:** ${text(block.where)}`);
      if(block.covers)add('**Objective coverage:** '+text(block.covers));
      add(text(block.why),fence(block.code));
      if(block.expected)add('**Expected result:** '+text(block.expected));
    }
    if(g.tests?.length){heading(5,'Expected host-policy tests');add(table(['Test','Addresses','Expected','Reason'],g.tests));}
    if(g.tips.length){heading(5,'Troubleshooting checks');add(g.tips.map(t=>'- '+text(t)).join('\n'));}
    if(g.sources.length){
      heading(5,'Command references');
      add(g.sources.map(key=>{const s=COMMAND_SOURCES[key];if(!s)throw Error('Unknown command source: '+key);return '- '+link(s.title,s.url);}).join('\n'));
    }
    heading(4,'Additional concept example');
    add('This may use older IOS syntax or an illustrative text diagram. Use the platform-labeled guide above for the intended current lab context.',fence(l.example));
    heading(4,'Check your understanding');
    add(text(l.question),l.options.map((o,i)=>`- **${String.fromCharCode(65+i)}.** ${text(o)}`).join('\n'));
    add('<details>\n<summary>Answer and explanation</summary>\n\n'+`**${String.fromCharCode(65+l.answer)}. ${text(l.options[l.answer])}**\n\n${text(l.explanation)}\n\n</details>`);
    const next=LESSONS[LESSONS.indexOf(l)+1];
    if(next)add('Next objective: '+link(`${next.id} ${next.title}`,'#'+anchor('objective',next.id)));
  }
}
heading(2,'Sources and reading limits');
add('- '+link('Cisco v1.1 exam blueprint',BLUEPRINT_SOURCE),'- '+link(BOOKS[1].title+' · ISBN '+BOOKS[1].isbn,BOOKS[1].url),'- '+link(BOOKS[2].title+' · ISBN '+BOOKS[2].isbn,BOOKS[2].url),'- '+link('Full textbook alignment findings and source list',base+'textbook-alignment-review.md'));
add('The textbook comparison uses publisher contents, selected public samples, published errata and Cisco references. Full paid volumes were not supplied for page-by-page comparison. Chapter references identify suggested reading; they do not establish equal textbook depth or exam readiness. The explanations and questions here are independently authored.');
const learning=out.join('\n').replace(/\n+$/,'\n');
const readmePath=path.join(root,'README.md');
const currentReadme=fs.readFileSync(readmePath,'utf8').replace(/\r\n/g,'\n');
if(currentReadme.split(begin).length!==2||currentReadme.split(end).length!==2)throw Error('README needs exactly one generated curriculum stats block.');
const start=currentReadme.indexOf(begin),finish=currentReadme.indexOf(end)+end.length;
if(start>=finish)throw Error('README generated markers are out of order.');
const readme=currentReadme.slice(0,start)+stats+currentReadme.slice(finish);
const csvCell=value=>'"'+String(value??'').replaceAll('"','""')+'"';
const catalog=[['id','domain','objective','concept','question'],...QUESTIONS.map(q=>[q.id,DOMAINS.find(d=>d.id===q.d).name,q.lesson,q.concept,q.q])].map(row=>row.map(csvCell).join(',')).join('\n')+'\n';
const coverage=coverageDocuments();
let stale=false;
for(const [name,expected] of [['README.md',readme],['LEARNING_PATH.md',learning],['public/question-bank-catalog.csv',catalog],['public/assessment-coverage-report.md',coverage.markdown],['public/assessment-coverage.csv',coverage.csv]]){
  const file=path.join(root,name),current=fs.existsSync(file)?fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n'):null;
  if(current===expected){console.log(name+': current');continue;}
  if(check){console.error(name+': out of date');stale=true;}
  else{fs.writeFileSync(file,expected);console.log(name+': updated');}
}
if(stale){console.error('Run npm run docs:sync and commit the updated documentation.');process.exitCode=1;}
